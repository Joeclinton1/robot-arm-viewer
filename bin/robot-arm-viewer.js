#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { createReadStream, existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { createServer } from 'node:http';
import { dirname, extname, join, normalize, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const clients = new Set();
let lastConfigure = null;
let lastAction = null;

const args = new Map();
for (let i = 2; i < process.argv.length; i += 1) {
  const arg = process.argv[i];
  if (!arg.startsWith('--')) continue;
  const [key, inlineValue] = arg.slice(2).split('=', 2);
  if (inlineValue !== undefined) {
    args.set(key, inlineValue);
  } else {
    const next = process.argv[i + 1];
    args.set(key, next && !next.startsWith('--') ? process.argv[++i] : 'true');
  }
}

const host = args.get('host') || '127.0.0.1';
const port = Number(args.get('port') || 8020);

const contentTypes = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.urdf': 'application/xml; charset=utf-8',
  '.stl': 'model/stl',
  '.obj': 'text/plain; charset=utf-8',
  '.mtl': 'text/plain; charset=utf-8',
  '.dae': 'model/vnd.collada+xml',
  '.glb': 'model/gltf-binary',
  '.png': 'image/png',
};

function sendJson(res, status, value) {
  const body = JSON.stringify(value);
  res.writeHead(status, {
    'content-type': 'application/json; charset=utf-8',
    'content-length': Buffer.byteLength(body),
  });
  res.end(body);
}

function broadcast(value) {
  const body = Buffer.from(JSON.stringify(value));
  const header = body.length < 126
    ? Buffer.from([0x81, body.length])
    : Buffer.from([0x81, 126, body.length >> 8, body.length & 0xff]);

  for (const socket of [...clients]) {
    try {
      socket.write(Buffer.concat([header, body]));
    } catch {
      clients.delete(socket);
      socket.destroy();
    }
  }
}

function readBody(req) {
  return new Promise((resolveBody, rejectBody) => {
    const chunks = [];
    req.on('data', chunk => chunks.push(chunk));
    req.on('end', () => {
      try {
        resolveBody(chunks.length ? JSON.parse(Buffer.concat(chunks).toString('utf8')) : {});
      } catch (error) {
        rejectBody(error);
      }
    });
    req.on('error', rejectBody);
  });
}

function generateCombinedMtl(filePath) {
  const sidecarDir = dirname(filePath);
  const meshDir = join(sidecarDir, 'meshes');
  if (!existsSync(meshDir) || !statSync(meshDir).isDirectory()) return false;

  const materials = new Map();
  for (const entry of readdirSync(meshDir)) {
    if (!entry.toLowerCase().endsWith('.mtl')) continue;
    const content = readFileSync(join(meshDir, entry), 'utf8').replace(/\r\n/g, '\n');
    const blocks = content.split(/\n(?=newmtl\s+)/g);
    for (const block of blocks) {
      const match = block.match(/(?:^|\n)newmtl\s+([^\n\r]+)/);
      if (!match) continue;
      const name = match[1].trim();
      if (!materials.has(name)) materials.set(name, block.trim());
    }
  }

  if (materials.size === 0) return false;
  const body = [
    '# Combined material library generated by robot-arm-viewer',
    ...[...materials.values()],
    '',
  ].join('\n\n');
  writeFileSync(filePath, body, 'utf8');
  return true;
}

const server = createServer(async (req, res) => {
  if (req.method === 'GET' && req.url === '/health') {
    sendJson(res, 200, { ok: true, clients: clients.size });
    return;
  }

  if (req.method === 'POST' && (req.url === '/api/configure' || req.url === '/api/action')) {
    try {
      const body = await readBody(req);
      const message = { type: req.url.endsWith('/configure') ? 'configure' : 'action', ...body };
      if (message.type === 'configure') lastConfigure = message;
      if (message.type === 'action') lastAction = message;
      broadcast(message);
      sendJson(res, 200, { ok: true, clients: clients.size });
    } catch (error) {
      sendJson(res, 400, { ok: false, error: String(error.message || error) });
    }
    return;
  }

  if (req.method !== 'GET') {
    sendJson(res, 405, { ok: false, error: 'method not allowed' });
    return;
  }

  const urlPath = decodeURIComponent((req.url || '/').split('?')[0]);
  const relativePath = urlPath === '/' ? 'index.html' : urlPath.slice(1);
  const filePath = normalize(join(root, relativePath));
  if (
    filePath.startsWith(root) &&
    !existsSync(filePath) &&
    filePath.endsWith(`${normalize('/pincopen/materials.combined.mtl').replace(/^[/\\]/, '')}`)
  ) {
    generateCombinedMtl(filePath);
  }
  if (!filePath.startsWith(root) || !existsSync(filePath) || !statSync(filePath).isFile()) {
    res.writeHead(404);
    res.end('not found');
    return;
  }

  res.writeHead(200, {
    'content-type': contentTypes[extname(filePath).toLowerCase()] || 'application/octet-stream',
    'cache-control': ['.html', '.js', '.css'].includes(extname(filePath).toLowerCase())
      ? 'no-store'
      : 'public, max-age=3600',
  });
  createReadStream(filePath).pipe(res);
});

server.on('upgrade', (req, socket) => {
  if (req.url !== '/control') {
    socket.destroy();
    return;
  }

  const key = req.headers['sec-websocket-key'];
  if (!key) {
    socket.destroy();
    return;
  }

  const accept = createHash('sha1')
    .update(`${key}258EAFA5-E914-47DA-95CA-C5AB0DC85B11`)
    .digest('base64');

  socket.write(
    'HTTP/1.1 101 Switching Protocols\r\n' +
    'Upgrade: websocket\r\n' +
    'Connection: Upgrade\r\n' +
    `Sec-WebSocket-Accept: ${accept}\r\n\r\n`
  );
  clients.add(socket);
  if (lastConfigure) broadcast(lastConfigure);
  if (lastAction) broadcast(lastAction);
  socket.on('close', () => clients.delete(socket));
  socket.on('error', () => clients.delete(socket));
});

server.listen(port, host, () => {
  console.log(`robot-arm-viewer listening at http://${host}:${port}`);
});
